//Equality Comprison

//Normal comparison(==), compares only the value and not the datatype
console.log(3 == '3')
console.log('shr' == 'shr')

//Strict comparison (===), compares both value and the datatype
console.log(3 === '3')
console.log('shr' === 'shr')

//null vs undefined
let x
console.log(typeof x)
let y = null
console.log(typeof y)
console.log(x == y)
console.log(x === y)
